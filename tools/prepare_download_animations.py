"""Convert the three approved GIFs into bounded, predecoded PNG sprite sheets.

Only resizing and atlas packing are performed. Pillow's GIF decoder composites
disposal frames; colors, backgrounds, transparency and every frame duration are
retained. No GIF decoder or asset-file access is needed during a download.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path

from PIL import Image


SOURCE_NAMES = (
    "dizpemq-ffea66a3-e508-4a4d-b1d4-aa7a00dae633.gif",
    "tumblr_60f63f0974b637fb6e052eb9f70368db_11065475_400.gif",
    "happy-dance-animated-gif-image-1-2.gif",
)
MAX_ATLAS = 1024
CACHE_BYTES = 1280 * 720 * 4
MEMORY_CAP = 12 * 1024 * 1024


def build(source_dir: Path, project: Path, height: int = 104) -> dict:
    destination = project / "content" / "animations"
    destination.mkdir(parents=True, exist_ok=True)
    atlases, clips = [], []
    for clip_index, filename in enumerate(SOURCE_NAMES):
        source = source_dir / filename
        with Image.open(source) as gif:
            width = max(1, round(gif.width * height / gif.height))
            columns, rows = MAX_ATLAS // width, MAX_ATLAS // height
            if not columns or not rows:
                raise ValueError("Frame exceeds the atlas size limit")
            capacity = columns * rows
            frames, total_ms = [], 0
            sheet = None
            for index in range(gif.n_frames):
                if index % capacity == 0:
                    count = min(capacity, gif.n_frames - index)
                    sheet_columns = min(columns, count)
                    sheet_rows = (count + columns - 1) // columns
                    sheet = Image.new("RGBA", (sheet_columns * width, sheet_rows * height))
                    name = f"download-{clip_index + 1}-{index // capacity + 1}.png"
                    atlases.append({"file": name, "width": sheet.width, "height": sheet.height})
                gif.seek(index)
                # Seek/convert preserves GIF disposal, palette and alpha rather
                # than treating delta frames as independent images.
                decoded = gif.convert("RGBA").resize((width, height), Image.Resampling.LANCZOS)
                duration = int(gif.info.get("duration", 100))
                if duration <= 0:
                    raise ValueError(f"{filename}: frame {index} has no positive duration")
                total_ms += duration
                x, y = (index % capacity % columns) * width, (index % capacity // columns) * height
                sheet.paste(decoded, (x, y))
                frames.append([len(atlases) - 1, x, y, width, height, total_ms])
                if index % capacity == capacity - 1 or index == gif.n_frames - 1:
                    sheet.save(destination / name, optimize=True)
            clips.append({
                "source": filename,
                "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
                "source_width": gif.width,
                "source_height": gif.height,
                "source_loop": gif.info.get("loop", 1),
                "frame_count": gif.n_frames,
                "duration_ms": total_ms,
                "frames": frames,
            })
    atlas_bytes = sum(a["width"] * a["height"] * 4 for a in atlases)
    if atlas_bytes + CACHE_BYTES > MEMORY_CAP:
        raise ValueError(f"Decoded assets + redraw cache exceed 12 MiB: {atlas_bytes + CACHE_BYTES}")
    # Only remove obsolete sheets produced by this converter, after the new
    # set passes its budget. Never touch unrelated artwork in this directory.
    current_files = {atlas["file"] for atlas in atlases}
    for old_sheet in destination.iterdir():
        if re.fullmatch(r"download-[123]-[0-9]+\.png", old_sheet.name) and old_sheet.name not in current_files:
            old_sheet.unlink()
    manifest = {
        "format": 1,
        "frame_height": height,
        "atlas_rgba_bytes": atlas_bytes,
        "redraw_cache_rgba_bytes": CACHE_BYTES,
        "total_rgba_bytes": atlas_bytes + CACHE_BYTES,
        "atlases": atlases,
        "clips": clips,
    }
    (destination / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    lines = ["// Generated by tools/prepare_download_animations.py. Do not edit.",
             "#pragma once", '#include "download_animation.hpp"', "#include <array>",
             "namespace unbound::download_animation::assets {",
             f"inline constexpr std::array<Atlas,{len(atlases)}> Atlases{{{{"]
    for atlas in atlases:
        lines.append(f'    {{"fs:/vol/content/animations/{atlas["file"]}",{atlas["width"]},{atlas["height"]}}},')
    lines.append("}};")
    for index, clip in enumerate(clips):
        lines.append(f"inline constexpr Frame Frames{index}[]={{")
        lines.extend("    {" + ",".join(map(str, frame)) + "}," for frame in clip["frames"])
        lines.append("};")
    lines.append(f"inline constexpr std::array<Clip,{len(clips)}> Clips{{{{")
    for index, clip in enumerate(clips):
        lines.append(f'    {{Frames{index},{clip["frame_count"]},{clip["duration_ms"]}}},')
    lines.extend(["}};", f"inline constexpr std::size_t TotalRgbaBytes={atlas_bytes + CACHE_BYTES};",
                  "static_assert(TotalRgbaBytes<=12*1024*1024);", "} // namespace unbound::download_animation::assets", ""])
    (project / "include" / "download_animation_assets.hpp").write_text("\n".join(lines), encoding="utf-8")
    return manifest


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="Directory containing the three original GIFs")
    parser.add_argument("--project", type=Path, default=Path(__file__).resolve().parent.parent)
    parser.add_argument("--height", type=int, default=104)
    args = parser.parse_args()
    result = build(args.source, args.project, args.height)
    print(json.dumps({key: value for key, value in result.items() if key not in ("clips", "atlases")}, indent=2))
    for clip in result["clips"]:
        print(f'{clip["source"]}: {clip["frame_count"]} frames, {clip["duration_ms"]} ms')
